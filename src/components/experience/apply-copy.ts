const copy: Record<Language, ApplyCopy> = { en, fr, de, it };

/** Project-interest options: the Experience page's four groups (with their tags) plus "not sure yet". */
export function interestOptions(lang: Language): { value: XpInterest; title: string; tags: string }[] {
  const groups = experienceCopy(lang).projects.groups;
  const keys: XpInterest[] = ['web', 'ai', 'business', 'content'];
  return [
    ...keys.map((value, i) => ({ value, title: groups[i].title, tags: groups[i].items.join(' · ') })),
    { value: 'unsure', title: copy[lang].interests.unsure, tags: '' },
  ];
}

export function applyCopy(lang: Language): ApplyCopy {
  return copy[lang];
}
